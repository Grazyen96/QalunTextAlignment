#!/usr/bin/env python3
"""Generate index.bundle.js — a single-file fallback for UXP's module loader.

The panel normally loads src/main.js and lets UXP's CommonJS loader resolve the
relative requires. That path is now correct (explicit .js extensions), but it is
the one thing we cannot test from Linux. This flattens the same sources into one
script so the Windows-side fix, if it is ever needed, is a one-line edit in
index.html:

    <script src="src/main.js">  ->  <script src="index.bundle.js">

Run: python3 uxp-panel/build_bundle.py
"""

import re
from pathlib import Path

PANEL_DIR = Path(__file__).resolve().parent
SRC_DIR = PANEL_DIR / "src"
OUT = PANEL_DIR / "index.bundle.js"

# Dependency order: a module must appear after everything it uses at call time.
MODULES = ["spec.js", "build.js", "captions.js", "exporter.js", "main.js"]

# main.js calls build.importPackageMedia(...) etc. In the flat bundle those are
# plain top-level functions, so rebuild the namespace object it expects.
BUILD_NAMESPACE = """
// Flattened: main.js expects build.* — rebuild the namespace from the top-level
// functions that build.js contributed to this bundle.
const build = {
  importPackageMedia,
  createSequence,
  placeAudio,
  placeOverlays,
  applyHighlightKeyframes,
  addAyahMarkers,
  findProjectItemByName,
};
"""

RE_LOCAL_REQUIRE = re.compile(r"^[ \t]*(?:const|let|var)\s+.*=\s*require\(\"\./.*\);[ \t]*\n", re.M)
RE_HOST_REQUIRE = re.compile(
    r"^[ \t]*(?:const|let|var)\s+\w+\s*=\s*require\(\"(?:premierepro|uxp)\"\);[ \t]*\n", re.M
)
RE_MODULE_EXPORTS = re.compile(r"^module\.exports\s*=\s*\{.*?\};[ \t]*\n", re.M | re.S)
RE_USE_STRICT = re.compile(r"^[ \t]*\"use strict\";[ \t]*\n", re.M)


def strip(source: str) -> str:
    source = RE_MODULE_EXPORTS.sub("", source)
    source = RE_LOCAL_REQUIRE.sub("", source)
    source = RE_HOST_REQUIRE.sub("", source)
    source = RE_USE_STRICT.sub("", source)
    return source.strip("\n")


def main() -> None:
    parts = [
        '"use strict";',
        "// GENERATED by build_bundle.py — do not edit. Edit src/*.js and re-run.",
        "",
        'const ppro = require("premierepro");',
        'const uxp = require("uxp");',
    ]
    for name in MODULES:
        if name == "main.js":
            parts.append(BUILD_NAMESPACE)
        body = strip((SRC_DIR / name).read_text(encoding="utf-8"))
        parts.append(f"\n// ---------- {name} ----------\n{body}")

    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
