"""Where a lecture's episode lives on disk: its intro, its recitation, its outro.

The intro and outro clips are copied beside the project, named by their
content, so the project folder can be moved or shared with the clips inside it,
and choosing the same clip twice keeps one copy. The recitation is only
referenced, by its project path: it is a live job of its own, which can be
corrected and rendered again, and the episode should use it as it is then.

Paths are stored relative to the project folder when inside it and absolute
otherwise, the rule the look's image follows.

An intro or outro can instead be generated by Qalun (``intro_generated`` /
``outro_generated``): a small dict of settings, from which the clip is made at
render time in the lecture's look. A part is a clip or generated, never both;
generated settings win over a clip path a hand-edited file also holds.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Any

from qurantext.core.title_cards import MAX_SECONDS, MIN_SECONDS, STYLES
from qurantext.core.tracked_link import PLATFORMS
from qurantext.jobs.look_assets import copy_by_content
from qurantext.jobs.project import Project, _resolve_path, _store_path

__all__ = [
    "EPISODE_SUFFIXES",
    "DEFAULT_PHRASE",
    "EpisodeChoice",
    "GeneratedIntro",
    "GeneratedOutro",
    "episode_dir_for",
    "import_episode_clip",
    "project_episode",
    "seed_project_episode",
    "set_project_episode",
]

#: The clip types an intro or outro can be.
EPISODE_SUFFIXES = (".mp4", ".mov", ".mkv", ".webm")

#: The episode keys the choice owns, in the order they play around the lecture.
_PART_KEYS = ("intro", "recitation", "outro")
#: The clip parts whose original file name is kept beside the stored path: the
#: copy beside the project is named by its content (``3f2a9c1b2d4e.mp4``),
#: which would tell the person nothing about which clip it is.
_CLIP_PARTS = ("intro", "outro")
_NAME_KEYS = tuple(f"{part}_name" for part in _CLIP_PARTS)
#: The keys holding a part's generated settings, in place of its clip.
_GENERATED_KEYS = tuple(f"{part}_generated" for part in _CLIP_PARTS)

#: The outro's closing phrase until the person writes another.
DEFAULT_PHRASE = "جزاكم الله خيرًا"


def _text(value: Any, default: str) -> str:
    return value if isinstance(value, str) else default


def _style(value: Any) -> str:
    return value if isinstance(value, str) and value in STYLES else "fade"


def _seconds(value: Any, default: float) -> float:
    """*value* as a length in seconds, clamped to 3–10; *default* for anything not a number."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return default
    value = float(value)
    if not math.isfinite(value):
        return default
    return min(MAX_SECONDS, max(MIN_SECONDS, value))


@dataclass(frozen=True, slots=True)
class GeneratedIntro:
    """A generated intro: the channel (or speaker) *name* above the lecture's surah and ayat.

    The title line is not stored: it is read from the lecture's cards when the
    clip is made, so it follows corrections. Built tolerantly: an unknown
    *style* is ``fade`` and *seconds* is clamped to 3–10.
    """

    name: str = ""
    style: str = "fade"
    seconds: float = 5.0

    def __post_init__(self) -> None:
        object.__setattr__(self, "name", _text(self.name, ""))
        object.__setattr__(self, "style", _style(self.style))
        object.__setattr__(self, "seconds", _seconds(self.seconds, 5.0))

    def to_dict(self) -> dict[str, Any]:
        return {"name": self.name, "style": self.style, "seconds": self.seconds}

    @classmethod
    def from_dict(cls, data: Any) -> GeneratedIntro | None:
        """The settings *data* holds, each junk field at its default; None when not a dict."""
        if not isinstance(data, dict):
            return None
        return cls(
            name=_text(data.get("name"), ""),
            style=data.get("style"),  # type: ignore[arg-type]  # normalised on init
            seconds=_seconds(data.get("seconds"), 5.0),
        )


@dataclass(frozen=True, slots=True)
class GeneratedOutro:
    """A generated outro: a closing *phrase* and, with a *link*, its tracked QR code.

    *link* is kept as the person typed it (checked by the dialog, and again
    when the clip is made); empty means no QR code. *platform* is where the
    video is published, the link's ``utm_source``. Built tolerantly: an
    unknown *style* is ``fade``, an unknown *platform* ``youtube``, and
    *seconds* is clamped to 3–10.
    """

    phrase: str = DEFAULT_PHRASE
    link: str = ""
    platform: str = "youtube"
    style: str = "fade"
    seconds: float = 6.0

    def __post_init__(self) -> None:
        object.__setattr__(self, "phrase", _text(self.phrase, DEFAULT_PHRASE))
        object.__setattr__(self, "link", _text(self.link, ""))
        platform = self.platform if self.platform in PLATFORMS else "youtube"
        object.__setattr__(self, "platform", platform)
        object.__setattr__(self, "style", _style(self.style))
        object.__setattr__(self, "seconds", _seconds(self.seconds, 6.0))

    def to_dict(self) -> dict[str, Any]:
        return {
            "phrase": self.phrase,
            "link": self.link,
            "platform": self.platform,
            "style": self.style,
            "seconds": self.seconds,
        }

    @classmethod
    def from_dict(cls, data: Any) -> GeneratedOutro | None:
        """The settings *data* holds, each junk field at its default; None when not a dict."""
        if not isinstance(data, dict):
            return None
        platform = data.get("platform")
        return cls(
            phrase=_text(data.get("phrase"), DEFAULT_PHRASE),
            link=_text(data.get("link"), ""),
            platform=platform if isinstance(platform, str) else "youtube",
            style=data.get("style"),  # type: ignore[arg-type]  # normalised on init
            seconds=_seconds(data.get("seconds"), 6.0),
        )


@dataclass(frozen=True, slots=True)
class EpisodeChoice:
    """What plays around the lecture: each part is a path, or None when not chosen.

    *intro* and *outro* are video clips; *recitation* is a recitation job's
    project file, whose current video is used. *intro_name* and *outro_name*
    are the clips' original file names, for showing: the stored copies are
    named by their content. None when unknown (or the part is not chosen).

    *intro_generated* and *outro_generated* are a generated part's settings.
    A part is a clip or generated: generated settings win, and the part's clip
    and name are dropped when both are given.
    """

    intro: Path | None = None
    recitation: Path | None = None
    outro: Path | None = None
    intro_name: str | None = None
    outro_name: str | None = None
    intro_generated: GeneratedIntro | None = None
    outro_generated: GeneratedOutro | None = None

    def __post_init__(self) -> None:
        for part in _CLIP_PARTS:
            if getattr(self, f"{part}_generated") is not None:
                object.__setattr__(self, part, None)
                object.__setattr__(self, f"{part}_name", None)

    def is_generated(self, part: str) -> bool:
        """Whether *part* (``intro`` or ``outro``) is generated rather than a clip."""
        return getattr(self, f"{part}_generated", None) is not None

    @property
    def parts_set(self) -> tuple[str, ...]:
        """The names of the parts chosen (a clip or generated), in playing order."""
        return tuple(
            key
            for key in _PART_KEYS
            if getattr(self, key) is not None or getattr(self, f"{key}_generated", None)
        )

    @property
    def is_empty(self) -> bool:
        """True when no part is chosen: the lecture is rendered alone."""
        return not self.parts_set


def episode_dir_for(project_path: Path) -> Path:
    """``job.qalun.json`` keeps its episode clips in ``job.qalun.episode``."""
    return Path(project_path).with_suffix(".episode")


def import_episode_clip(project_path: Path, source: Path) -> Path:
    """Copy the clip *source* beside the project, named by its content; return the copy.

    See :func:`~qurantext.jobs.look_assets.copy_by_content`, whose errors it
    raises: ``ValueError`` for a type not in :data:`EPISODE_SUFFIXES`,
    ``FileNotFoundError`` for a missing clip, another ``OSError`` for anything
    the file system refuses.
    """
    return copy_by_content(source, episode_dir_for(project_path), suffixes=EPISODE_SUFFIXES)


def _project_dir(project: Project) -> Path | None:
    return Path(project.path).parent if project.path is not None else None


def project_episode(project: Project) -> EpisodeChoice:
    """The project's episode, with each path resolved against the project folder.

    The file can be hand-edited or written by a newer build, so a value that is
    not a non-empty string reads as "not chosen" rather than failing, and so
    does an intro or outro whose type is not one of :data:`EPISODE_SUFFIXES`.
    Generated settings that are not a dict read as "not generated"; a junk
    field in them reads as its default.
    """
    episode = project.episode if isinstance(project.episode, dict) else {}
    folder = _project_dir(project)

    def part(key: str) -> Path | None:
        value = episode.get(key)
        if not isinstance(value, str) or not value:
            return None
        path = _resolve_path(value, folder)
        if key != "recitation" and path.suffix.lower() not in EPISODE_SUFFIXES:
            return None
        return path

    choice = EpisodeChoice(*(part(key) for key in _PART_KEYS))

    def name(clip: str) -> str | None:
        value = episode.get(f"{clip}_name")
        if getattr(choice, clip) is None or not isinstance(value, str) or not value.strip():
            return None
        return value

    return replace(
        choice,
        intro_name=name("intro"),
        outro_name=name("outro"),
        intro_generated=GeneratedIntro.from_dict(episode.get("intro_generated")),
        outro_generated=GeneratedOutro.from_dict(episode.get("outro_generated")),
    )


def set_project_episode(
    project: Project, choice: EpisodeChoice, *, project_dir: Path | None = None
) -> None:
    """Store *choice* in the project's episode, keeping the keys that are not a part.

    Each path is stored relative to *project_dir* when given, else to the
    folder of ``project.path`` (a project not yet saved names the folder it
    will be saved in), and absolute when it is outside that folder or when no
    folder is known: a project with no file and no *project_dir*. A part not
    chosen is removed rather than written as null, so an empty choice returns
    the episode, and with it the content hash, to what it was before any was
    chosen. A generated part stores its settings (``intro_generated``) and no
    clip, so choosing one removes the other.
    """
    folder = Path(project_dir) if project_dir is not None else _project_dir(project)
    # _store_path(..., None) is absolute: a relative path with nothing known to
    # be relative to would be read later against the project's folder and miss.
    current = project.episode if isinstance(project.episode, dict) else {}
    owned = (*_PART_KEYS, *_NAME_KEYS, *_GENERATED_KEYS)
    episode = {k: v for k, v in current.items() if k not in owned}
    for key in _PART_KEYS:
        value = getattr(choice, key)
        if value is not None:
            episode[key] = _store_path(Path(value), folder)
    for clip in _CLIP_PARTS:
        name = getattr(choice, f"{clip}_name")
        if getattr(choice, clip) is not None and name:
            episode[f"{clip}_name"] = name
        generated = getattr(choice, f"{clip}_generated")
        if generated is not None:
            episode[f"{clip}_generated"] = generated.to_dict()
    project.episode = episode


def seed_project_episode(
    project: Project,
    project_path: Path,
    intro: Path | None,
    outro: Path | None,
    *,
    names: tuple[str | None, str | None] = (None, None),
    generated: tuple[GeneratedIntro | None, GeneratedOutro | None] = (None, None),
) -> list[tuple[str, dict[str, Any]]]:
    """Give a new lecture about to be saved at *project_path* the default *intro* and *outro*.

    Each clip is copied beside the project, as choosing it in the Episode
    dialog would; the recitation is left unchosen, since a default one would
    be the wrong recitation for every lecture but one. A default clip that has
    gone missing, or that cannot be copied, is not a reason to lose a new job:
    it is left out, and a notice says so.

    Returns the notices as ``(i18n key, values)`` pairs for the caller to say
    in the person's language (``episode.seed.missing``,
    ``episode.seed.failed``); the job layer does not translate, as
    :class:`~qurantext.jobs.episode.EpisodeError` does not. The one value,
    ``part``, is ``"intro"`` or ``"outro"``: the default's own file name is a
    content hash in the app's folder, which would tell the person nothing.
    *names* are the defaults' original file names, kept beside the copies so
    the Episode dialog can show them. *generated* are the default generated
    intro and outro settings: a part with them is generated, nothing is copied
    for it, and its default clip (there should be none) is not used. Never
    raises for a clip that is missing or refused.
    """
    notices: list[tuple[str, dict[str, Any]]] = []

    def copied(part: str, clip: Path | None) -> Path | None:
        if clip is None:
            return None
        try:
            return import_episode_clip(project_path, Path(clip))
        except FileNotFoundError:
            notices.append(("episode.seed.missing", {"part": part}))
        except (ValueError, OSError):
            notices.append(("episode.seed.failed", {"part": part}))
        return None

    intro_generated, outro_generated = generated
    choice = EpisodeChoice(
        intro=None if intro_generated is not None else copied("intro", intro),
        outro=None if outro_generated is not None else copied("outro", outro),
        intro_name=names[0] or None,
        outro_name=names[1] or None,
        intro_generated=intro_generated,
        outro_generated=outro_generated,
    )
    if not choice.is_empty:
        set_project_episode(project, choice, project_dir=Path(project_path).parent)
    return notices
